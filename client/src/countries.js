export function flagEmoji(iso) {
  if (!iso || iso.length !== 2) return '🏳️';
  return String.fromCodePoint(...[...iso.toUpperCase()].map((c) => 127397 + c.charCodeAt(0)));
}

// Split a stored full international number into { iso, dial, local } for the picker.
export function splitWhatsApp(value) {
  let d = (value || '').replace(/\D/g, '');
  if (d.startsWith('00')) d = d.slice(2);
  let best = null;
  for (const [iso, dial] of COUNTRIES) {
    if (d.startsWith(dial) && (!best || dial.length > best[1].length)) best = [iso, dial];
  }
  if (!best) return { iso: 'EG', dial: '20', local: d };
  return { iso: best[0], dial: best[1], local: d.slice(best[1].length) };
}

// Combine a chosen dial code with a typed local number into wa.me-ready digits.
export function joinWhatsApp(dial, local) {
  const l = (local || '').replace(/\D/g, '').replace(/^0+/, '');
  return l ? dial + l : '';
}

// Final safety normalization before building the wa.me link.
export function normalizeWhatsApp(value) {
  let d = (value || '').replace(/\D/g, '');
  if (d.startsWith('00')) d = d.slice(2);
  return d;
}
